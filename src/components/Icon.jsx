export default function Icon({ name, size = 18, strokeWidth = 1.8, className, style, ...rest }) {
  const Cmp = ICONS[name] || Info;
  return (
    <Cmp
      size={size}
      strokeWidth={strokeWidth}
      className={className}
      style={{ flexShrink: 0, ...style }}
      aria-hidden="true"
      {...rest}
    />
  );
}

/**
 * Renderiza un "valor de icono" sin importar en qué formato venga:
 *  - nombre lucide en texto  ('billete')  -> <Icon>
 *  - elemento ya montado     (<Icon .../>) -> tal cual
 *  - vacío                   ('')         -> nada
 * Evita que los nombres sueltos se vean como texto plano.
 */
export function Ico({ name, size = 18, ...rest }) {
  if (isValidElement(name)) return name;
  if (typeof name === 'string' && name.trim()) {
    return <Icon name={name.trim()} size={size} {...rest} />;
  }
  return null;
}
